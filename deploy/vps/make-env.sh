#!/usr/bin/env bash
# Create /opt/aerar/.env on the VPS with fresh secrets and a fresh Base Sepolia payer wallet.
# Secrets are generated on the server and written straight to the file (mode 600); only public values are printed.
# Never overwrites an existing .env. Usage (as root, after npm ci): bash deploy/vps/make-env.sh aerar.example.org
set -euo pipefail

DOMAIN="${1:?usage: make-env.sh <domain>}"
APP_DIR=/opt/aerar
ENV_FILE="$APP_DIR/.env"
cd "$APP_DIR"

if [[ -e "$ENV_FILE" ]]; then
  echo "$ENV_FILE already exists; leaving it untouched."
  exit 0
fi

rand() { openssl rand -hex "$1"; }
DB_PASS="$(rand 24)"

# Database role and database (localhost only).
if ! sudo -u postgres psql -tAc "SELECT 1 FROM pg_roles WHERE rolname='aerar'" | grep -q 1; then
  sudo -u postgres psql -q -c "CREATE ROLE aerar LOGIN PASSWORD '$DB_PASS'"
else
  sudo -u postgres psql -q -c "ALTER ROLE aerar PASSWORD '$DB_PASS'"
fi
sudo -u postgres psql -tAc "SELECT 1 FROM pg_database WHERE datname='aerar'" | grep -q 1 \
  || sudo -u postgres createdb -O aerar aerar
# Throwaway database for the public scenario runs (wiped before every run; never the real ledger).
sudo -u postgres psql -tAc "SELECT 1 FROM pg_database WHERE datname='aerar_sandbox'" | grep -q 1 \
  || sudo -u postgres createdb -O aerar aerar_sandbox

# Fresh wallets: payer (key kept in .env) and demo provider (receive-only; key discarded).
read -r PAYER_KEY PAYER_ADDR PAYTO_ADDR < <(node --input-type=module -e '
import { generatePrivateKey, privateKeyToAccount } from "viem/accounts";
const k = generatePrivateKey();
const payTo = privateKeyToAccount(generatePrivateKey()).address;
console.log(k, privateKeyToAccount(k).address, payTo);
')

umask 077
cat > "$ENV_FILE" <<ENV
# Generated by deploy/vps/make-env.sh on $(date -u +%Y-%m-%dT%H:%MZ). TESTNET ONLY (Base Sepolia).
DATABASE_URL=postgres://aerar:$DB_PASS@127.0.0.1:5432/aerar
SANDBOX_DATABASE_URL=postgres://aerar:$DB_PASS@127.0.0.1:5432/aerar_sandbox
PAYER_PRIVATE_KEY=$PAYER_KEY
BASE_SEPOLIA_RPC_URL=
DEMO_PAYTO_ADDRESS=$PAYTO_ADDR
DEMO_PROVIDER_HOST=$DOMAIN
X402_FACILITATOR_URL=https://x402.org/facilitator
OPERATOR_PASSWORD=$(rand 12)
SESSION_SECRET=$(rand 32)
AERAR_ORG_ID=org_demo
ENV
chown aerar:aerar "$ENV_FILE"
chmod 600 "$ENV_FILE"

echo "Wrote $ENV_FILE (mode 600, owner aerar)."
echo "Payer wallet address (fund with Base Sepolia test USDC at faucet.circle.com): $PAYER_ADDR"
echo "Demo provider address (receives demo payments): $PAYTO_ADDR"
echo "Operator password: run  grep OPERATOR_PASSWORD $ENV_FILE  on the server yourself."
